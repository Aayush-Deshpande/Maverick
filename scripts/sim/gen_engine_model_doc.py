"""Generate docs/physics/ENGINE_MODEL.txt (card M1-16, P Step 1.6, deliverable 3).

Equations come from the backend/sim module docstrings (one source with the code); the constants table, calibration
results and validation tables are computed from the configs and the calibrated plant at generation time.
Run: python scripts/sim/gen_engine_model_doc.py
"""
import ast
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from backend.physics.engine_config import available_engines, load_engine_config   # noqa: E402
from backend.sim.atmosphere import Atmosphere                                       # noqa: E402
from backend.sim.engine import MeanValueEngine                                      # noqa: E402
from backend.sim.maps import best_bsfc, build_maps                                  # noqa: E402
from backend.sim.params import physics_blocks                                       # noqa: E402

MODULES = ["atmosphere", "induction", "turbo", "fuel", "combustion", "engine", "rotor", "thermal", "electrical",
           "vibration", "plant", "faults", "sensors", "source", "maps"]
ALTITUDES_FT = [0, 5000, 10000, 15000, 20000]
RULE = "=" * 117


def docstring(module: str) -> str:
    text = (ROOT / "backend" / "sim" / f"{module}.py").read_text(encoding="utf-8")
    return ast.get_docstring(ast.parse(text)) or ""


def constants_table() -> list:
    lines = ["Shared defaults (configs/physics/defaults.json). Engine overrides are listed per engine below.", ""]
    first = available_engines()[0]
    defaults = physics_blocks(first)
    own = {e: load_engine_config(e) for e in available_engines()}
    for section, entries in defaults.items():
        lines.append(f"[{section}]")
        for name, v in entries.items():
            lines.append(f"  {name:<40} {str(v.get('value')):>12}  {v.get('status', ''):<11} {v.get('ref', '')}")
        lines.append("")
    import json
    for e in own:
        block = json.loads((ROOT / "configs" / "engines" / f"{e}.json").read_text(encoding="utf-8")).get("physics")
        if not block:
            continue
        lines.append(f"Overrides for {e}:")
        for section, entries in block.items():
            for name, v in entries.items():
                lines.append(f"  {section}.{name:<34} {str(v.get('value')):>12}  {v.get('status', ''):<11} {v.get('ref', '')}")
        lines.append("")
    return lines


def calibration_table() -> list:
    lines = [f"{'engine':<18}{'eta_i':>7}{'TO kW cfg':>11}{'TO kW sim':>11}{'MC kW cfg':>11}{'MC kW sim':>11}"
             f"{'BSFC rated':>12}{'BSFC best':>11}  g/kWh, ISA sea level"]
    for e in available_engines():
        cfg = load_engine_config(e)
        m = MeanValueEngine(cfg)
        sl = Atmosphere.at(0.0)
        to = m.steady_point(100, cfg.rated_rpm, sl)
        t = cfg.turbo if cfg.is_turbocharged else None
        mc_target = t.map_continuous_max_kpa * 1000 if t is not None and t.map_continuous_max_kpa else None
        mc = m.steady_point(100, cfg.max_continuous_rpm, sl, map_target_pa=mc_target)   # TCU continuous MAP
        bsfc = to.mdot_fuel_kg_s * 3.6e6 / (to.brake_w / 1000.0)
        maps = build_maps(cfg)
        lines.append(f"{e:<18}{m.combustion.eta_i:>7.3f}{cfg.rated_power_kw:>11.1f}{to.brake_w / 1000:>11.1f}"
                     f"{(cfg.max_continuous_power_kw or float('nan')):>11.1f}{mc.brake_w / 1000:>11.1f}"
                     f"{bsfc:>12.0f}{best_bsfc(maps):>11.0f}")
    return lines


def altitude_table() -> list:
    lines = [f"{'engine':<18}" + "".join(f"{a:>10} ft" for a in ALTITUDES_FT) + "   (WOT, rated rpm, ISA; kW)"]
    for e in available_engines():
        cfg = load_engine_config(e)
        m = MeanValueEngine(cfg)
        row = [m.steady_point(100, cfg.rated_rpm, Atmosphere.at(a)).brake_w / 1000 for a in ALTITUDES_FT]
        lines.append(f"{e:<18}" + "".join(f"{p:>13.1f}" for p in row))
    return lines


def main() -> None:
    out = [RULE, "ANUMAAN ENGINE MODEL (backend/sim)  -  generated by scripts/sim/gen_engine_model_doc.py on "
           + date.today().isoformat(), RULE, "",
           "Evidence class: SIMULATION. Every number below is computed from configs/ and the calibrated model when",
           "this file is generated; edit the configs or code and re-run the script, never this file.", "",
           "1. EQUATIONS (from the module docstrings)", ""]
    for i, mod in enumerate(MODULES, start=1):
        out += [f"1.{i} backend/sim/{mod}.py", "-" * 60, docstring(mod), ""]
    out += ["2. CALIBRATION RESULTS (R 21.5)", "-" * 60] + calibration_table() + [""]
    out += ["3. VALIDATION: POWER VS ALTITUDE", "-" * 60] + altitude_table() + [""]
    out += ["4. CONSTANTS WITH PROVENANCE (D16)", "-" * 60] + constants_table()
    out += ["5. VALIDATION TESTS", "-" * 60,
            "T-PHY-1..7, 9, 11: tests/sim/test_engine_power.py, test_thermal.py, test_turbo.py, test_plant.py, ...",
            "T-FLT-1 signature matrix: docs/physics/t_flt_1_report.csv (scripts/sim/run_t_flt_1.py, slow marker).",
            "T-DYN-2/3/6/8: tests/dynamic/test_dynamic_rule.py. Open physics questions: PROGRESS.txt Questions 6-8.", ""]
    path = ROOT / "docs" / "physics" / "ENGINE_MODEL.txt"
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {path} ({len(out)} lines)")


if __name__ == "__main__":
    main()
